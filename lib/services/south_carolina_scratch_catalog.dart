  static SouthCarolinaScratchGame _game(
    String id,
    String name,
    List<List<int>> tiers, {
    int groupedOfficialEntries = 1,
  }) {
    return SouthCarolinaScratchGame(
      id: id,
      name: name,
      groupedOfficialEntries: groupedOfficialEntries,
      prizeTiers: tiers
          .map(
            (tier) => SouthCarolinaScratchPrizeTier(
              amount: tier[0],
              claimedYesterday: tier[1],
            ),
          )
          .toList(growable: false),
    );
  }
